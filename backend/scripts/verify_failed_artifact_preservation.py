"""Controlled Failed Generation Verification Script for AEGIS AI.

Executes a controlled simulated run:
- Generates a React Portfolio workspace with source files.
- Forces a validation failure.
- Verifies all 10 criteria specified in Section 18.
"""

from __future__ import annotations

import asyncio
import json
import sys
import tempfile
import zipfile
from datetime import UTC, datetime
from pathlib import Path
from unittest.mock import MagicMock

# Ensure backend is on sys.path
backend_path = Path(__file__).resolve().parent.parent
if str(backend_path) not in sys.path:
    sys.path.insert(0, str(backend_path))

from app.core.config import settings
from app.core.enums import AgentRole, ArtifactKind, RunStatus
from app.packaging.diagnostics import (
    MODEL_ROUTING_CONFIG,
    build_diagnostics,
    build_generation_status_readme,
    count_preserved_files,
)
from app.packaging.workspace import ProjectWorkspace
from app.packaging.zip_builder import ZipPackager
from app.schemas.generation import RunArtifactInfo, RunDetail
from app.services.orchestration_service import RunOrchestrator
from app.workflow.engine import WorkflowOutcome
from app.workflow.memory import SharedProjectMemory, ValidationResult


async def run_controlled_failed_generation_verification() -> bool:
    print("=" * 70)
    print("AEGIS AI — CONTROLLED FAILED GENERATION VERIFICATION")
    print("=" * 70)

    # Criterion 9 & 10 check: request limits & model/API key config unchanged
    print("\n[Check 9 & 10] Verifying limits and model architecture...")
    from app.llm.budget import TaskBudgetState
    from app.llm.agent_model_registry import SLOT_DEFAULT_MODELS
    budget_state = TaskBudgetState(task_id="test-check")
    assert budget_state.target_limit == 10, f"Expected soft limit 10, got {budget_state.target_limit}"
    assert budget_state.hard_limit == 15, f"Expected hard limit 15, got {budget_state.hard_limit}"
    assert SLOT_DEFAULT_MODELS["PLANNER_API_KEY01"] == "nvidia/nemotron-3-super-120b-a12b"
    assert SLOT_DEFAULT_MODELS["FRONTEND_API_KEY01"] == "gemini-3.6-flash"
    assert SLOT_DEFAULT_MODELS["BACKEND_API_KEY01"] == "gemini-3.6-flash"
    assert SLOT_DEFAULT_MODELS["DATABASE_API_KEY01"] == "gemini-3.6-flash"
    assert SLOT_DEFAULT_MODELS["QA_API_KEY01"] == "nvidia/nemotron-3-super-120b-a12b"
    assert SLOT_DEFAULT_MODELS["REVIEW_API_KEY01"] == "nvidia/nemotron-3-super-120b-a12b"
    assert SLOT_DEFAULT_MODELS["DEBUG_API_KEY01"] == "nvidia/nemotron-3-super-120b-a12b"
    print("  [OK] Soft limit = 10, Hard limit = 15")
    print(f"  [OK] Planner model = {SLOT_DEFAULT_MODELS['PLANNER_API_KEY01']}")
    print(f"  [OK] Frontend model = {SLOT_DEFAULT_MODELS['FRONTEND_API_KEY01']}")

    with tempfile.TemporaryDirectory() as tmp_dir:
        packager = ZipPackager(artifact_root=tmp_dir)
        orchestrator = RunOrchestrator(packager=packager)

        run_id = "controlled-fail-run-1234"
        memory = SharedProjectMemory(
            run_id=run_id,
            project_id="proj-react-portfolio",
            project_name="React Portfolio",
            project_slug="react-portfolio",
            idea="Create a simple React portfolio.",
        )

        # 1. Simulate files generated by agents
        print("\n[Simulating generation] Agents generate files...")
        memory.workspace.write("package.json", json.dumps({"name": "react-portfolio", "version": "1.0.0"}))
        memory.workspace.write("tsconfig.json", json.dumps({"compilerOptions": {"jsx": "react-jsx"}}))
        memory.workspace.write(
            "frontend/src/App.tsx",
            "import React from 'react';\nexport function App() {\n  return <div>Portfolio</div>;\n}\n",
        )
        memory.workspace.write(
            "frontend/src/components/Hero.tsx",
            "export function Hero() { return <section>Hi, I am an engineer</section>; }\n",
        )
        memory.workspace.write(
            "frontend/src/components/Projects.tsx",
            "export function Projects() { return <section>My Work</section>; }\n",
        )

        print(f"  [OK] Preserved files count: {len(memory.workspace)} files generated")

        # 2. Force validation failure
        print("\n[Simulating validation failure] Forcing validation failure on 'npm run typecheck'...")
        val_result = ValidationResult(
            passed=False,
            stack="frontend",
            total_commands=3,
            failed_commands=1,
            failures=[
                {
                    "command": "npm run typecheck",
                    "exit_code": 2,
                    "stdout": "",
                    "stderr": "src/App.tsx(2,10): error TS2304: Cannot find name 'UnknownProperty'.",
                    "category": "type_error",
                    "responsible_agent": "frontend_engineer",
                }
            ],
        )
        memory.final_qa_result = val_result
        memory.release_eligible = False

        outcome = WorkflowOutcome(
            plan=MagicMock(),
            failed=True,
            failure_reason="Release blocked: project failed validation or final QA gate.",
        )

        # 3. Create partial package via orchestrator
        print("\n[Packaging] Invoking _create_partial_package...")
        package = orchestrator._create_partial_package(
            run_id=run_id,
            memory=memory,
            outcome=outcome,
            failed_stage="Final QA",
            failed_command="npm run typecheck",
            exit_code=2,
        )

        # Verification items:
        # 1. Generation reports failure
        print("\n1. Verifying generation reports failure...")
        assert outcome.failed is True
        print(f"  [OK] outcome.failed = {outcome.failed}, reason: {outcome.failure_reason}")

        # 2. Release remains blocked
        print("2. Verifying release remains blocked...")
        assert memory.release_eligible is False
        print(f"  [OK] memory.release_eligible = {memory.release_eligible}")

        # 3. Partial ZIP exists
        print("3. Verifying partial ZIP exists...")
        assert package is not None
        assert package.path.exists()
        print(f"  [OK] Partial ZIP exists at {package.path} ({package.size_bytes} bytes)")

        # 4. ZIP can be opened
        print("4. Verifying ZIP can be opened...")
        with zipfile.ZipFile(package.path, "r") as archive:
            namelist = archive.namelist()
            print(f"  [OK] Successfully opened ZIP ({len(namelist)} entries found)")

            # 5. Generated files are inside
            print("5. Verifying generated files are inside...")
            assert "aegis-generation-partial/project/frontend/src/App.tsx" in namelist
            assert "aegis-generation-partial/project/frontend/src/components/Hero.tsx" in namelist
            assert "aegis-generation-partial/project/frontend/src/components/Projects.tsx" in namelist
            assert "aegis-generation-partial/project/package.json" in namelist
            app_content = archive.read("aegis-generation-partial/project/frontend/src/App.tsx").decode("utf-8")
            assert "Portfolio" in app_content
            print("  [OK] All 5 workspace files present under aegis-generation-partial/project/")

            # 6. Diagnostics are inside
            print("6. Verifying diagnostics are inside...")
            diag_report_path = "aegis-generation-partial/aegis-diagnostics/generation-report.json"
            val_failures_path = "aegis-generation-partial/aegis-diagnostics/validation-failures.json"
            routing_path = "aegis-generation-partial/aegis-diagnostics/model-routing.json"
            assert diag_report_path in namelist
            assert val_failures_path in namelist
            assert routing_path in namelist

            diag_data = json.loads(archive.read(diag_report_path).decode("utf-8"))
            assert diag_data["status"] == "failed"
            assert diag_data["release_eligible"] is False
            assert diag_data["failed_stage"] == "Final QA"
            print("  [OK] Diagnostics JSON files present and valid")

            # 7. README says RELEASE BLOCKED
            print("7. Verifying README says RELEASE BLOCKED...")
            readme_path = "aegis-generation-partial/README-GENERATION-STATUS.md"
            assert readme_path in namelist
            readme_text = archive.read(readme_path).decode("utf-8")
            assert "RELEASE BLOCKED" in readme_text
            assert "Failed command: npm run typecheck" in readme_text
            assert "Exit code: 2" in readme_text
            assert "This is NOT production-ready" in readme_text
            print("  [OK] README-GENERATION-STATUS.md verified with RELEASE BLOCKED")

        # 8. UI / API exposes the download
        print("8. Verifying API / UI schema exposes download...")
        artifact_info = RunArtifactInfo(
            available=True,
            type="partial",
            name="project-partial.zip",
        )
        detail = RunDetail(
            id=run_id,
            project_id="proj-react-portfolio",
            status="failed",
            phase="failed",
            progress=60,
            file_count=len(memory.workspace),
            duration_seconds=18.5,
            created_at=datetime(2026, 1, 1, 0, 0, 0, tzinfo=UTC),
            finished_at=datetime(2026, 1, 1, 0, 0, 18, tzinfo=UTC),
            release_eligible=False,
            artifact=artifact_info,
        )
        dump = detail.model_dump()
        assert dump["status"] == "failed"
        assert dump["release_eligible"] is False
        assert dump["artifact"]["available"] is True
        assert dump["artifact"]["type"] == "partial"
        assert dump["artifact"]["name"] == "project-partial.zip"
        print("  [OK] API RunDetail correctly returns artifact info with available=True, type='partial'")

    print("\n" + "=" * 70)
    print("ALL 10 VERIFICATION CRITERIA PASSED SUCCESSFULLY!")
    print("=" * 70)
    return True


if __name__ == "__main__":
    success = asyncio.run(run_controlled_failed_generation_verification())
    if not success:
        sys.exit(1)
