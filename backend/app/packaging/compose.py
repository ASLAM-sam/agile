"""Docker Compose file generation.

Built deterministically from the adapters that are actually in play, so the
services, ports, health checks and dependency ordering are always consistent
with the code that was generated.
"""

from __future__ import annotations

from typing import Any

from app.adapters.base import ScaffoldContext
from app.adapters.registry import AdapterRegistry
from app.workflow.memory import SharedProjectMemory


def build_compose_file(
    registry: AdapterRegistry,
    memory: SharedProjectMemory,
    ctx: ScaffoldContext,
) -> str:
    """Render `docker-compose.yml`, or an empty string if nothing to compose."""
    services: dict[str, dict[str, Any]] = {}
    volumes: dict[str, dict[str, Any]] = {}

    if memory.needs_database and memory.tech_stack.database:
        adapter = registry.database(memory.tech_stack.database)
        service = adapter.compose_service(ctx)
        if service is not None:
            services["db"] = service
            for volume in service.get("volumes", []):
                name = str(volume).split(":", 1)[0]
                if not name.startswith((".", "/")):
                    volumes[name] = {}

    if memory.needs_backend and memory.tech_stack.backend:
        adapter = registry.backend(memory.tech_stack.backend)
        service = adapter.compose_service(ctx)
        if "db" not in services:
            service.pop("depends_on", None)
        services["api"] = service

    if memory.needs_frontend and memory.tech_stack.frontend:
        adapter = registry.frontend(memory.tech_stack.frontend)
        service = adapter.compose_service(ctx)
        if "api" not in services:
            service.pop("depends_on", None)
        services["web"] = service

    if not services:
        return ""

    document: dict[str, Any] = {"services": services}
    if volumes:
        document["volumes"] = volumes

    header = (
        f"# Docker Compose — {memory.project_name}\n"
        "# Generated by Aegis AI.\n"
        "#\n"
        "# Start everything:  docker compose up --build\n"
        "# Stop everything:   docker compose down\n"
        "#\n"
        "# Copy each .env.example to .env before the first run.\n\n"
    )
    return header + _to_yaml(document)


def _to_yaml(value: Any, indent: int = 0) -> str:
    """Minimal YAML emitter for the plain data Compose files contain.

    Avoids a PyYAML dependency for a fully known, nesting-limited structure.
    Handles dicts, lists, strings, bools and numbers — nothing else appears here.
    """
    pad = "  " * indent
    lines: list[str] = []

    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(item, dict):
                if not item:
                    lines.append(f"{pad}{key}: {{}}")
                else:
                    lines.append(f"{pad}{key}:")
                    lines.append(_to_yaml(item, indent + 1))
            elif isinstance(item, list):
                if not item:
                    lines.append(f"{pad}{key}: []")
                else:
                    lines.append(f"{pad}{key}:")
                    for element in item:
                        if isinstance(element, dict):
                            rendered = _to_yaml(element, indent + 2).lstrip()
                            lines.append(f"{pad}  - {rendered}")
                        else:
                            lines.append(f"{pad}  - {_scalar(element)}")
            else:
                lines.append(f"{pad}{key}: {_scalar(item)}")
    else:  # pragma: no cover - top level is always a mapping
        lines.append(f"{pad}{_scalar(value)}")

    return "\n".join(line for line in lines if line.strip())


def _scalar(value: Any) -> str:
    """Render a scalar, quoting where YAML would otherwise misread it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return str(value)

    text = str(value)
    needs_quotes = (
        not text
        or text[0] in "!&*[]{}>|%@`#,?:-"
        or ": " in text
        or text.strip() != text
        or text.lower() in {"yes", "no", "true", "false", "on", "off", "null", "~"}
        or (text.replace(".", "", 1).isdigit())
    )
    if needs_quotes:
        escaped = text.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return text
